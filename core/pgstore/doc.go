// Package pgstore is a tenant-scoped PostgreSQL + pgvector index behind golib's search port: a
// search.Store[int64, *View] whose views are Semantic, Signaler and Lister, built on golib's dao
// alone (no SQL of its own beyond its migrations).
//
// Every table's key starts with the tenant, every join between them carries it, every upsert
// conflicts on a tenant-qualified key, and every statement, reads and writes alike, is filtered by
// the Store's tenant. Embeddings are keyed by (tenant, model, text hash), so tenants never share a
// vector and a switch of one tenant's model leaves another's untouched.
//
// Each View is one REPEATABLE READ, READ ONLY transaction, so every retriever and presentation field
// it answers reads one snapshot. Lexical search matches a stored tsvector generated by the
// rag_english configuration (Snowball English stemming with no stop-word removal: every query word
// stays required), title (class A), breadcrumb (B), tags (C) and body (D), and ranks with
// ts_rank_cd against the bound query — an approximation of the local store's bm25 weights, not
// parity; semantic search scans
// exactly, ordered by cosine distance to the bound vector over documents ready under the active
// model, and answers search.ErrModelChanged for any other model. Filters sit in the same WHERE as
// the match, so they apply before the rank and the limit; ties fall to path order (byte order)
// and then the ordinal.
//
// Each chunk has a kind, a section or an abstract (Document.Kinds); WithSectionsOnly leaves the
// abstracts out of Lexical and Semantic.
//
// Access: ViewWithin reads within an access scope, a map of document facet fields to the values
// a caller may see. Every retrieval of its View (Lexical, Semantic, List, Signals, and
// SemanticState's count) ANDs it in SQL, apart from the search.Filter: within a field the values
// are ORed, across fields ANDed, and no filter or query facet can widen it. An empty scope is
// ErrNoAccess. View is unscoped. A tenant's access fields are its Policy (SetPolicy, Policy).
//
// Ingest state, for a server that indexes a database source into a tenant page by page: a Batch
// moves the tenant's (updated_at, id) Cursor, records its last Refresh, and quarantines and
// releases failed source rows, all in the same transaction as the page's documents, so a crash
// replays at most the page it interrupted and a failed row is retried rather than passed for good.
// Store.Cursor, Refreshed and Quarantined read them back.
//
// Migrate applies the schema through dao/deploy, recording it in its own ledger table. Every object
// is created and found through the connection's search_path: WithSchema sets it on every
// connection a pool opens, and EnsureSchema creates the schema, which must exist before Migrate.
//
// Concurrency: a Store is safe for concurrent use. A View is valid only inside its fn and belongs to
// one goroutine; so does a Batch, which is one transaction. Writes conflict per document
// (ErrWriteRace); keeping a tenant to one writer is the caller's (the enterprise server holds an
// advisory lock on a dedicated connection).
